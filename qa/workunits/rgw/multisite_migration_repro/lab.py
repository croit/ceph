class LabError(RuntimeError):
    """An actionable error whose message contains no credential-bearing argv."""


def redact(text, credentials=()):
    """Redact both lab credentials and credentials generated by vstart."""
    text = str(text or "")
    for value in sorted(set(credentials), key=len, reverse=True):
        if value:
            text = text.replace(value, "<redacted>")
    text = re.sub(
        r'(?i)("(?:access_key|secret_key|secret|token|authorization)"\s*:\s*)'
        r'"(?:\\.|[^"\\])*"',
        r'\1"<redacted>"', text,
    )
    text = re.sub(
        r"(?im)((?:--)?(?:access[-_]key|secret(?:[-_]key)?|aws_access_key_id|"
        r"aws_secret_access_key|AWSAccessKeyId)\s*=\s*)([^\s,]+)",
        r"\1<redacted>", text,
    )
    text = re.sub(
        r'''(?i)(--(?:access[-_]key|secret(?:[-_]key)?)\s+)("[^"\n]*"|'[^'\n]*'|\S+)''',
        r"\1<redacted>", text,
    )
    text = re.sub(r"(?im)(authorization\s*[:=]\s*)[^\r\n]+",
                  r"\1<redacted>", text)
    text = re.sub(r"(?im)^(\s*key\s*=\s*)[^\r\n]+", r"\1<redacted>", text)
    text = re.sub(r"(?im)^(\s*(?:access|secret)\s+key:\s*)\S+",
                  r"\1<redacted>", text)
    return re.sub(r"(?i)(https?://)[^/\s@]+@", r"\1<redacted>@", text)


def private_directory(path):
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    path.chmod(0o700)
    return path


def private_write(path, text):
    """Atomically write state/diagnostics without a world-readable interval."""
    path = Path(path)
    private_directory(path.parent)
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            os.fchmod(output.fileno(), 0o600)
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
        path.chmod(0o600)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def timestamp():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


class CommandError(subprocess.CalledProcessError):
    def __init__(self, node, result):
        super().__init__(result.returncode, "<redacted command>",
                         output=node.redact(result.stdout),
                         stderr=node.redact(result.stderr))
        self.node_name = node.name

    def __str__(self):
        return "{}: command failed (exit {}); see bootstrap.log".format(
            self.node_name, self.returncode)


class CommandTimeout(subprocess.TimeoutExpired):
    def __init__(self, node, timeout):
        super().__init__("<redacted command>", timeout)
        self.node_name = node.name

    def __str__(self):
        return "{}: command timed out after {} seconds; see bootstrap.log".format(
            self.node_name, self.timeout)


